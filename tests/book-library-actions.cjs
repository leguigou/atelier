// Library shortcuts use an isolated database and cover desktop and mobile.
const {chromium}=require('playwright');
const {spawn}=require('node:child_process');
const path=require('node:path');
const assert=require('node:assert/strict');
(async()=>{
  const fixture=spawn(process.env.PYTHON||'python',[path.join(__dirname,'reader_fixture.py')],{stdio:['ignore','pipe','pipe']});
  fixture.stderr.on('data',s=>process.stderr.write(s));let browser;
  try{
    const base=await new Promise((resolve,reject)=>{fixture.stdout.once('data',s=>resolve(s.toString().trim()));fixture.once('exit',code=>reject(Error('Fixture exited '+code)))});
    browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{})});
    for(const width of [1280,390,320]){
      const context=await browser.newContext({viewport:{width,height:900}}),page=await context.newPage(),errors=[];
      page.on('pageerror',e=>errors.push(e.message));
      await page.goto(base);await page.locator('.project-book').first().waitFor();
      const displayBook=await (await context.request.get(base+'/api/book?book_id=book-main')).json();
      displayBook.title='Ton idée vaut 0 €';displayBook.author='Moi';
      assert.equal((await context.request.post(base+'/api/book',{data:displayBook})).status(),200);
      await page.reload();
      const actionMenu=page.locator('.project-book-menu').filter({has:page.locator('[data-duplicate-book="book-main"]')});
      await actionMenu.locator('summary').waitFor();
      const geometry=await actionMenu.evaluate(menu=>{const card=menu.closest('.project-book').getBoundingClientRect(),button=menu.getBoundingClientRect(),actions=menu.closest('.project-book').querySelector('.project-book-actions').getBoundingClientRect();return {menuTop:button.top-card.top,menuRight:card.right-button.right,actionsTop:actions.top,menuBottom:button.bottom}});
      assert(geometry.menuTop<30);assert(geometry.menuRight<30);assert(geometry.menuBottom<geometry.actionsTop);
      await page.screenshot({path:path.join(process.env.TEMP,`atelier-library-${width}.png`)});
      assert(await page.locator('[data-duplicate-book="book-main"]').isHidden());
      await actionMenu.locator('summary').click();
      assert(await page.locator('[data-duplicate-book="book-main"]').isVisible());
      assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
      await page.screenshot({path:path.join(process.env.TEMP,`atelier-library-menu-${width}.png`)});
      await page.keyboard.press('Escape');
      assert(await page.locator('[data-duplicate-book="book-main"]').isHidden());
      await actionMenu.locator('summary').click();
      const original=await (await context.request.get(base+'/api/book?book_id=book-main')).json();
      const initialBooks=await (await context.request.get(base+'/api/books')).json();
      await page.locator('[data-duplicate-book="book-main"]').click();
      await page.waitForFunction(count=>document.querySelectorAll('.project-book').length===count+1,initialBooks.length);
      const books=await (await context.request.get(base+'/api/books')).json();
      const copy=books.find(b=>!initialBooks.some(old=>old.id===b.id));assert(copy);
      const duplicated=await (await context.request.get(base+'/api/book?book_id='+copy.id)).json();
      assert.deepEqual(duplicated.chapters,original.chapters);
      assert.equal(duplicated.title,original.title+' — copie');
      await page.locator('[data-read-book="'+copy.id+'"]').click();
      await page.locator('#pagePosition').filter({hasText:/\d+ \/ \d+/}).waitFor();
      await page.locator('#nextPage').click();
      await page.locator('#pageContent [data-read-block]').first().waitFor();
      assert.equal(await page.evaluate(()=>reading.book_id),copy.id);
      await page.locator('#pageContent [data-read-block]').first().click();
      await page.locator('#readerEdit').click();await page.locator('#readerEditText').waitFor();
      await page.locator('#readerEditText').fill('Modification dans la copie '+width);
      await page.locator('#readerSaveResume').click();await page.locator('#readerPanel').waitFor({state:'detached'});
      assert.deepEqual((await (await context.request.get(base+'/api/book?book_id=book-main')).json()).chapters,original.chapters);
      await page.locator('#closeReading').click();await page.locator('[data-read-book="'+copy.id+'"]').waitFor();
      assert.equal(await page.evaluate(()=>view),'books');
      assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
      await page.locator('[data-read-book="book-main"]').click();await page.locator('#pagePosition').filter({hasText:/\d+ \/ \d+/}).waitFor();
      assert.equal(await page.evaluate(()=>reading.book_id),'book-main');
      await page.locator('#closeReading').click();
      const copyMenu=page.locator('.project-book-menu').filter({has:page.locator('[data-duplicate-book="'+copy.id+'"]')});
      await copyMenu.locator('summary').click();
      await page.locator('[data-book-action="details"][data-book-id="'+copy.id+'"]').click();
      await page.locator('#researchDetailsForm [name=title]').fill('Copie renommée '+width);
      await page.locator('#researchDetailsForm button[type=submit]').click();
      await page.locator('.project-book h2').filter({hasText:'Copie renommée '+width}).waitFor();
      await copyMenu.locator('summary').click();
      await page.locator('[data-book-action="download"][data-book-id="'+copy.id+'"]').click();
      await page.locator('[data-export="pdf"]').waitFor();await page.locator('#modal [data-close]').click();
      await copyMenu.locator('summary').click();
      await page.locator('[data-book-action="delete"][data-book-id="'+copy.id+'"]').click();
      assert(await page.locator('#confirmBookDelete').isDisabled());
      await page.locator('#modal [data-close]').click();
      assert.equal((await context.request.get(base+'/api/book?book_id='+copy.id)).status(),200);
      await copyMenu.locator('summary').click();
      await page.locator('[data-book-action="delete"][data-book-id="'+copy.id+'"]').click();
      await page.locator('#deleteBookConfirmation').fill('supprimer');await page.locator('#confirmBookDelete').click();
      await page.locator('[data-read-book="'+copy.id+'"]').waitFor({state:'detached'});
      assert.deepEqual((await (await context.request.get(base+'/api/book?book_id=book-main')).json()).chapters,original.chapters);
      assert.deepEqual(errors,[]);await context.close();
    }
    console.log('Library layout and actions passed at 1280, 390 and 320px: reading, editing, downloads, duplication and confirmed deletion.');
  }finally{await browser?.close();fixture.kill()}
})().catch(error=>{console.error(error);process.exitCode=1});
